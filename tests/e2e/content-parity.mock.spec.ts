import { test, expect, type Page } from '@playwright/test'

async function geometry(page: Page) {
  const selectors=['.app-shell__header','.import-page__heading','.input-steps','.import-upload__dropzone','.import-page__process']
  return Promise.all(selectors.map(selector=>page.locator(selector).boundingBox()))
}

test('013 centralized Debug is out of flow, preserves geometry and restores focus',async({page})=>{
  await page.goto('/imports')
  const main=page.getByRole('main')
  await expect(main).not.toContainText(/Minh họa|DEV\/QA|mock\.synthetic|Không phân tích file|Không ghi dữ liệu thật/)
  await expect(page.getByLabel('DEV scenario',{exact:true})).toHaveCount(0)
  const before=await geometry(page), scroll=await page.evaluate(()=>scrollY)
  const trigger=page.getByRole('button',{name:'Debug',exact:true})
  expect(await trigger.evaluate(element=>getComputedStyle(element).position)).toBe('fixed')
  await trigger.click()
  const debug=page.getByRole('dialog',{name:'UI State Preview',exact:true})
  await expect(debug.getByLabel('Role',{exact:true})).toBeVisible()
  await expect(debug.getByLabel('DEV scenario',{exact:true})).not.toBeVisible()
  await debug.getByText('Advanced diagnostics',{exact:true}).click()
  await expect(debug.getByLabel('DEV scenario',{exact:true})).toBeVisible()
  await expect(debug).toContainText('Mock — không phân tích file hoặc ghi dữ liệu thật')
  await debug.getByText('Import workspace',{exact:true}).click()
  await expect(debug).toContainText('"role": "OWNER"')
  expect(await geometry(page)).toEqual(before)
  expect(await page.evaluate(()=>scrollY)).toBe(scroll)
  await page.keyboard.press('Escape')
  await expect(debug).toHaveCount(0)
  await expect(trigger).toBeFocused()
  expect(await geometry(page)).toEqual(before)
})

test('013 row evidence is available only in Debug, including while a product drawer is open',async({page})=>{
  await page.addInitScript(()=>sessionStorage.setItem('shelfcash:dev-scenario:v1','staff-importer'))
  await page.goto('/imports')
  await page.getByLabel('Ngày dữ liệu',{exact:true}).fill('2026-10-11')
  await page.locator('input[type=file]').setInputFiles({name:'observed.csv',mimeType:'text/csv',buffer:Buffer.from('lot,on_hand\nLOT,10')})
  await page.getByRole('button',{name:'Phân tích dữ liệu',exact:true}).click()
  await expect(page.getByRole('heading',{name:'Phân tích hoàn tất',exact:true})).toBeVisible()
  await expect(page.getByRole('main')).not.toContainText(/Stage:|mock\.synthetic|Bindings và|schema\/|DEV\/QA/)
  await page.screenshot({path:'test-results/013-staff-analyze.png',fullPage:true})
  await page.getByRole('button',{name:'Kiểm tra cách hiểu',exact:true}).click()
  await page.screenshot({path:'test-results/013-staff-resolve.png',fullPage:true})
  await page.getByRole('button',{name:'Tạo Preview',exact:true}).click()
  const row=page.getByRole('row',{name:/Mở chi tiết dòng/}).first()
  await row.focus();await page.keyboard.press('Enter')
  const detail=page.getByRole('dialog',{name:'Chi tiết dòng dữ liệu',exact:true})
  await expect(detail).not.toContainText(/SOURCE_EXPLICIT|source_column_index|row_id|read-set|DTO/)
  await expect(detail.getByRole('heading',{name:'Giá trị trước → Giá trị sau'})).toBeVisible()
  await page.getByRole('button',{name:'Debug',exact:true}).click()
  const debug=page.getByRole('dialog',{name:'UI State Preview',exact:true})
  await debug.getByText('Advanced diagnostics',{exact:true}).click()
  await debug.getByText('Preview row / provenance / permissions',{exact:true}).click()
  await expect(debug).toContainText('SOURCE_EXPLICIT')
  await expect(debug).toContainText('row_id')
  await page.keyboard.press('Escape')
  await expect(debug).toHaveCount(0)
  await expect(detail).toBeVisible()
  await page.getByRole('button',{name:'Debug',exact:true}).click()
  await debug.getByRole('button',{name:'OWNER · Start',exact:true}).click()
  await expect(page.locator('[data-ui-preview="file-ready"]')).toBeVisible()
  await expect(detail).not.toBeVisible()
  await debug.getByRole('button',{name:'Return to current import',exact:true}).click()
  await debug.getByRole('button',{name:'Đóng Debug',exact:true}).click()
  await expect(detail).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(detail).toHaveCount(0)
})
