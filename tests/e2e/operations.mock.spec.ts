test('receipt dirty close keeps draft and combobox Escape closes only its popup',async({page})=>{
  await page.goto('/inventory');await page.getByRole('button',{name:'Nhận hàng / Tồn đầu kỳ'}).click()
  const d=page.getByRole('dialog',{name:'Nhận hàng vào Kho'})
  await d.getByLabel(/Số lượng thực nhận/).fill('2')
  await d.getByRole('combobox',{name:'Nguyên liệu',exact:true}).fill('Sữa')
  await expect(d.getByRole('listbox')).toBeVisible()
  await page.keyboard.press('Escape');await expect(d).toBeVisible();await expect(d.getByRole('listbox')).toHaveCount(0)
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog',{name:'Bạn có thay đổi chưa lưu'})).toBeVisible()
  await page.getByRole('button',{name:'Tiếp tục chỉnh sửa'}).click()
  await expect(d.getByLabel(/Số lượng thực nhận/)).toHaveValue('2')
  // Returning focus to the combobox can reopen its popup; use the drawer close action here.
  await d.getByRole('button',{name:'Đóng Nhận hàng vào Kho',exact:true}).click();await page.getByRole('button',{name:'Đóng và bỏ thay đổi'}).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
})
