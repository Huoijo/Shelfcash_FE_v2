import { test, expect, type Page } from '@playwright/test'

async function uploadAndAnalyze(page: Page, scenario: string) {
  await page.addInitScript(value => sessionStorage.setItem('shelfcash:dev-scenario:v1', value), scenario)
  await page.goto('/imports')
  await page.getByLabel('Ngày dữ liệu', { exact: true }).fill('2026-10-10')
  await page.locator('input[type=file]').setInputFiles({ name: 'observed-stock.csv', mimeType: 'text/csv', buffer: Buffer.from('ingredient,on_hand,unit\nMilk,10,l\nCoffee,8,kg\n') })
  await page.getByRole('button', { name: 'Phân tích dữ liệu', exact: true }).click()
  await page.getByRole('button', { name: /^Phân tích [0-9]+ file$/ }).click()
  await expect(page.getByRole('heading', { name: scenario === 'owner-ready' ? 'Chưa có profile phù hợp' : scenario === 'staff-importer' ? 'Phân tích hoàn tất' : 'Chưa có cách đọc đã được duyệt', exact: true })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Kiểm tra cách hiểu', exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: 'Kiểm tra cách hiểu', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Kiểm tra cách hiểu', exact: true })).toBeVisible()
  return new URL(page.url()).searchParams.get('import_id')
}
async function previewToCompletion(page: Page) {
  await page.getByRole('button', { name: 'Tạo Preview', exact: true }).click()
  await expect(page.getByRole('tab', { name: /Kiểm kê tồn kho/ })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Tiếp tục xác nhận' })).toBeDisabled()
  await page.getByRole('button', { name: 'Đọc thêm dòng Preview' }).click()
  await page.getByRole('button', { name: 'Tiếp tục xác nhận' }).click()
  await page.getByLabel('Lý do review (bắt buộc)').fill('Reviewed all retained rows')
  await page.getByLabel('Tôi đã đọc đủ dữ liệu, nguồn báo cáo, cách đọc và cảnh báo.').check()
  await page.getByRole('button', { name: 'Xác nhận đã kiểm tra' }).click()
  await page.getByLabel('Lý do nhập dữ liệu (bắt buộc)').fill('Count observed stock')
  await page.getByLabel('Tôi đã kiểm tra dữ liệu, cảnh báo và phạm vi nhập.').check()
  await page.getByRole('button', { name: 'Xác nhận và nhập dữ liệu' }).click()
  await expect(page.getByRole('heading', { name: 'Import đã hoàn tất', exact: true, level: 2 })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Khả năng lập kế hoạch', exact: true })).toBeVisible()
}

test('012 OWNER navigates Analyze → Resolve → reusable approval → Preview → Review → Commit → separate Readiness', async ({ page }) => {
  const id = await uploadAndAnalyze(page, 'owner-ready')
  await expect(page.getByText('OWNER FLOW', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Chỉnh mapping', exact: true }).click()
  await page.getByRole('button', { name: /^Lưu (mapping|đề xuất)$/ }).click()
  await page.getByRole('button', { name: 'Xem profile sẽ được lưu' }).click()
  await expect(page.getByRole('heading', { name: 'Duyệt cách đọc dữ liệu' })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Tạo Preview', exact: true })).toBeDisabled()
  await page.screenshot({ path: 'test-results/012-owner-review-profile.png', fullPage: true })
  await page.getByLabel('Lý do duyệt').fill('Owner reviewed reusable spec and evidence')
  await page.getByLabel('Tôi đã kiểm tra cách đọc đề xuất, bằng chứng và cách đọc đã duyệt (nếu có).').check()
  await page.getByRole('button', { name: 'Duyệt profile' }).click()
  await expect(page.getByRole('heading', { name: 'Profile đã được duyệt', exact: true })).toBeVisible()
  await page.screenshot({ path: 'test-results/012-owner-profile.png', fullPage: true })
  await previewToCompletion(page)
  expect(new URL(page.url()).searchParams.get('import_id')).toBe(id)
  await expect(page.getByText('Chưa đánh giá', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Kiểm tra Readiness', exact: true }).click()
  if(await page.getByRole('button', {name:'Kiểm tra Readiness',exact:true}).isVisible() && !(await page.getByText('Đủ dữ liệu', {exact:true}).isVisible())) await page.getByRole('button', {name:'Kiểm tra Readiness',exact:true}).click()
  await expect(page.getByText('Đủ dữ liệu', { exact: true })).toBeVisible()
  await page.screenshot({ path: 'test-results/012-owner-complete.png', fullPage: true })
})

test('012 STAFF reuses approved profile without Owner approval controls and completes import', async ({ page }) => {
  const id = await uploadAndAnalyze(page, 'staff-importer')
  await expect(page.getByText('STAFF FLOW', { exact: true })).toBeVisible()
  await expect(page.getByText('Đang dùng cách đọc đã duyệt', { exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Xem profile sẽ được lưu' })).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Duyệt profile' })).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Gửi Owner duyệt', exact: true })).toHaveCount(0)
  await previewToCompletion(page)
  expect(new URL(page.url()).searchParams.get('import_id')).toBe(id)
  await expect(page.getByRole('button', { name: 'Kiểm tra Readiness', exact: true })).toBeDisabled()
  await expect(page.getByText(/Bạn chưa có quyền xem đánh giá lập kế hoạch/)).toBeVisible()
  await page.screenshot({ path: 'test-results/012-staff-complete.png', fullPage: true })
})

for (const reject of [false, true]) test(`012 STAFF reusable change: submit → waiting → ${reject ? 'rejected → retained mapping → unchanged proposal resubmit blocked' : 'approved'} retains batch`, async ({ page }) => {
  const id = await uploadAndAnalyze(page, reject ? 'staff-rejected' : 'staff-approval')
  await page.getByRole('button', { name: 'Chỉnh mapping', exact: true }).click()
  await page.getByRole('button', { name: /^Lưu (mapping|đề xuất)$/ }).click()
  await page.getByRole('button', { name: 'Gửi Owner duyệt', exact: true }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Gửi Owner duyệt', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Đang chờ Owner duyệt', exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Chỉnh mapping', exact: true })).toHaveCount(0)
  if (reject) {
    await expect(page.getByText('Cần chỉnh lại cách hiểu', { exact: true })).toBeVisible()
    await page.getByRole('button', { name: 'Chỉnh lại', exact: true }).click()
    await page.getByRole('button', { name: 'Chỉnh mapping', exact: true }).click()
    await expect(page.getByRole('dialog').getByRole('button',{name:'Lưu mapping',exact:true})).toBeDisabled()
    await page.getByRole('dialog').getByRole('button',{name:'Hủy',exact:true}).click()
    await page.getByRole('button', { name: 'Gửi Owner duyệt', exact: true }).click()
    await page.getByRole('dialog').getByRole('button', { name: 'Gửi Owner duyệt', exact: true }).click()
    await expect(page.getByText('Đề xuất đã bị trả lại. Cần chỉnh cách hiểu trước khi gửi lại.',{exact:true})).toBeVisible()
    expect(new URL(page.url()).searchParams.get('import_id')).toBe(id)
    return
  }
  await expect(page.getByText('Cách đọc đã được duyệt', { exact: true })).toBeVisible()
  expect(new URL(page.url()).searchParams.get('import_id')).toBe(id)
  await expect(page.locator('input[type=file]')).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Duyệt profile' })).toHaveCount(0)
  await previewToCompletion(page)
})

test('012 unknown reopened import never creates a replacement draft on refresh', async ({ page }) => {
  await page.goto('/imports?import_id=00000000-0000-4000-8000-000000000999')
  await expect(page.getByText(/Chưa đọc được đúng lô trong URL/)).toBeVisible()
  await page.reload()
  expect(new URL(page.url()).searchParams.get('import_id')).toBe('00000000-0000-4000-8000-000000000999')
  await expect(page.getByRole('button', { name: 'Phân tích dữ liệu', exact: true })).toBeDisabled()
})

